#!/usr/bin/env bash
set -Eeuo pipefail

die() {
  printf 'INSTALL ABORTED: %s\n' "$*" >&2
  exit 1
}

command -v realpath >/dev/null || die "realpath is required"
command -v findmnt >/dev/null || die "findmnt is required"
command -v rclone >/dev/null || die "rclone is not installed"
command -v systemctl >/dev/null || die "systemctl is required"

repo_dir="$(cd "$(dirname "$(realpath "$0")")/.." && pwd -P)"
[[ -f "$repo_dir/systemd/user/google-drive-rclone.service" ]] ||
  die "Missing tracked systemd service"

[[ "$(findmnt -n --mountpoint /drive -o TARGET 2>/dev/null || true)" == "/drive" ]] ||
  die "/drive is not mounted; refusing to install"

[[ "$(findmnt -n --mountpoint /drive -o FSTYPE 2>/dev/null || true)" == "ext4" ]] ||
  die "/drive is not the expected ext4 filesystem"

[[ ! -L /drive/gdrive ]] || die "/drive/gdrive must not be a symlink"

if ! mkdir -p /drive/gdrive; then
  die "Cannot create /drive/gdrive. Fix its ownership/permissions first (e.g. sudo install -d -o $(id -un) -g $(id -gn) /drive/gdrive)."
fi
[[ -w /drive/gdrive ]] ||
  die "/drive/gdrive is not writable. Fix ownership/permissions first."

if ! rclone listremotes 2>/dev/null | grep -Fxq 'gdrive:'; then
  die "No rclone remote named gdrive: (configure it with rclone config)"
fi

if ! systemctl --user show-environment >/dev/null 2>&1; then
  die "systemd user manager unavailable; log in normally before installing"
fi

bin_dir="$HOME/.local/bin"
unit_dir="$HOME/.config/systemd/user"
mkdir -p "$bin_dir" "$unit_dir"

link_exact() {
  local source="$1" target="$2"
  if [[ -L "$target" ]]; then
    [[ "$(realpath "$target")" == "$source" ]] ||
      die "Refusing to replace a different symlink: $target"
  elif [[ -e "$target" ]]; then
    die "Refusing to replace an existing file: $target"
  fi
  ln -sfn "$source" "$target"
}

link_exact "$repo_dir/scripts/copy.sh" "$bin_dir/google-drive-rclone-copy"
link_exact "$repo_dir/systemd/user/google-drive-rclone.service" "$unit_dir/google-drive-rclone.service"
link_exact "$repo_dir/systemd/user/google-drive-rclone.timer" "$unit_dir/google-drive-rclone.timer"

# Avoid two independent downloaders if the previous chat-generated service
# was installed. Do not touch an unrelated legacy service.
legacy_service="$unit_dir/gdrive-archive.service"
if [[ -f "$legacy_service" ]] && grep -Fqx '# Generated by setup-gdrive-archive.yaml' "$legacy_service"; then
  systemctl --user disable --now gdrive-archive.timer 2>/dev/null || true
  systemctl --user stop gdrive-archive.service 2>/dev/null || true
  printf 'Disabled old chat-generated gdrive-archive job.\n'
elif systemctl --user is-active --quiet gdrive-archive.service ||
     systemctl --user is-enabled --quiet gdrive-archive.timer 2>/dev/null; then
  die "An unrecognized gdrive-archive job is active. Refusing to run duplicate downloaders."
fi

systemctl --user daemon-reload
systemctl --user enable --now google-drive-rclone.timer

printf '\nInstalled Google Drive archive.\n'
printf 'Source: gdrive:\nDestination: /drive/gdrive\n'
printf 'Rate limit: 512 KiB/s | Transfers: 1 | No local deletions or overwrites\n'
printf 'The timer starts the first pass automatically; no terminal must remain open.\n'
printf 'Status: systemctl --user status google-drive-rclone.timer\n'
